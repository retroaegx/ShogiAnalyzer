Q = "q"


def _s(text):
    out = []
    for tok in text.split():
        if tok.startswith("q:"):
            _, c, e = tok.split(":")
            out.append((Q, tuple(map(float, c.split(","))), tuple(map(float, e.split(",")))))
        else:
            out.append(tuple(map(float, tok.split(","))))
    return out


def _g(*strokes):
    return [_s(t) for t in strokes]


